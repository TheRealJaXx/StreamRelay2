@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun LatencyTestScreen(
    viewModel: CaptureViewModel,
    onChangeMode: () -> Unit,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    val localIp by viewModel.localIp.collectAsStateWithLifecycle()
    val txPort by viewModel.txPort.collectAsStateWithLifecycle()
    val connectedClients by viewModel.txConnectedClients.collectAsStateWithLifecycle()
    val isServerActive by viewModel.isTxServerActive.collectAsStateWithLifecycle()
    val txStats by viewModel.txStats.collectAsStateWithLifecycle()
    val testFps by viewModel.testFps.collectAsStateWithLifecycle()
    val testAudioTick by viewModel.testAudioTick.collectAsStateWithLifecycle()
    val testFramesGenerated by viewModel.testFramesGenerated.collectAsStateWithLifecycle()

    var isFullscreen by remember { mutableStateOf(false) }

    // Keep screen on while running latency test
    DisposableEffect(Unit) {
        val window = (context as? Activity)?.window
        window?.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
        onDispose {
            window?.clearFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
        }
    }

    if (isFullscreen) {
        // Fullscreen Mode for immediate side-by-side comparison
        Box(
            modifier = Modifier
                .fillMaxSize()
                .background(Color.Black)
                .clickable { isFullscreen = false }
        ) {
            IsolatedTestFeed(
                viewModel = viewModel,
                modifier = Modifier.fillMaxSize()
            )

            // Minimal Exit Floating Pill
            Surface(
                modifier = Modifier
                    .align(Alignment.TopEnd)
                    .padding(16.dp),
                shape = RoundedCornerShape(20.dp),
                color = Color.Black.copy(alpha = 0.65f),
                border = BorderStroke(1.dp, Color(0xFF334155))
            ) {
                Row(
                    modifier = Modifier
                        .clickable { isFullscreen = false }
                        .padding(horizontal = 14.dp, vertical = 8.dp),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(6.dp)
                ) {
                    Icon(
                        imageVector = Icons.Default.FullscreenExit,
                        contentDescription = "Exit Fullscreen",
                        tint = Color.White,
                        modifier = Modifier.size(18.dp)
                    )
                    Text(
                        text = "Exit Fullscreen",
                        color = Color.White,
                        style = MaterialTheme.typography.labelSmall
                    )
                }
            }
        }
    } else {
        Scaffold(
            modifier = modifier.fillMaxSize(),
            topBar = {
                CenterAlignedTopAppBar(
                    title = {
                        Column(horizontalAlignment = Alignment.CenterHorizontally) {
                            Text(
                                text = "Latency Test TX",
                                style = MaterialTheme.typography.titleLarge,
                                fontWeight = FontWeight.Bold
                            )
                            Text(
                                text = "Port $txPort · v${BuildConfig.VERSION_NAME}",
                                style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.primary
                            )
                        }
                    },
                    navigationIcon = {
                        IconButton(onClick = onChangeMode) {
                            Icon(
                                imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                                contentDescription = "Switch mode"
                            )
                        }
                    },
                    actions = {
                        IconButton(onClick = { viewModel.refreshLocalIp() }) {
                            Icon(
                                imageVector = Icons.Default.Refresh,
                                contentDescription = "Refresh IP"
                            )
                        }
                    },
                    colors = TopAppBarDefaults.centerAlignedTopAppBarColors(
                        containerColor = MaterialTheme.colorScheme.surface
                    )
                )
            }
        ) { innerPadding ->
            LazyColumn(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(innerPadding)
                    .padding(horizontal = 16.dp),
                verticalArrangement = Arrangement.spacedBy(16.dp)
            ) {
                // 1. Live Test Pattern Viewport Card
                item {
                    Card(
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(16.dp),
                        colors = CardDefaults.cardColors(containerColor = Color(0xFF0F172A)),
                        border = BorderStroke(1.5.dp, Color(0xFF334155))
                    ) {
                        Column(modifier = Modifier.padding(12.dp)) {
                            Row(
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(bottom = 8.dp),
                                horizontalArrangement = Arrangement.SpaceBetween,
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Row(
                                    verticalAlignment = Alignment.CenterVertically,
                                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                                ) {
                                    Box(
                                        modifier = Modifier
                                            .size(8.dp)
                                            .clip(CircleShape)
                                            .background(Color(0xFF34D399))
                                    )
                                    Text(
                                        text = "Live Synchronized Generator",
                                        style = MaterialTheme.typography.labelMedium,
                                        color = Color(0xFF94A3B8),
                                        fontWeight = FontWeight.Medium
                                    )
                                }

                                Row(
                                    modifier = Modifier
                                        .clip(RoundedCornerShape(8.dp))
                                        .clickable { isFullscreen = true }
                                        .padding(horizontal = 8.dp, vertical = 4.dp),
                                    verticalAlignment = Alignment.CenterVertically,
                                    horizontalArrangement = Arrangement.spacedBy(4.dp)
                                ) {
                                    Icon(
                                        imageVector = Icons.Default.Fullscreen,
                                        contentDescription = "Expand Fullscreen",
                                        tint = MaterialTheme.colorScheme.primary,
                                        modifier = Modifier.size(16.dp)
                                    )
                                    Text(
                                        text = "Fullscreen",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = MaterialTheme.colorScheme.primary,
                                        fontWeight = FontWeight.Bold
                                    )
                                }
                            }

                            Box(
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .aspectRatio(16f / 9f)
                                    .clip(RoundedCornerShape(10.dp))
                                    .background(Color.Black)
                            ) {
                                IsolatedTestFeed(
                                    viewModel = viewModel,
                                    modifier = Modifier.fillMaxSize()
                                )
                            }
                        }
                    }
                }

                // 2. Network Destination Card
                item {
                    TestNetworkCard(
                        localIp = localIp,
                        port = txPort,
                        connectedClients = connectedClients,
                        isServerActive = isServerActive
                    )
                }

                // 3. Frame Rate & Audio Controls Card
                item {
                    TestControlsCard(
                        currentFps = testFps,
                        audioTickEnabled = testAudioTick,
                        onSelectFps = { viewModel.setTestFps(it) },
                        onToggleAudioTick = { viewModel.setTestAudioTick(it) }
                    )
                }

                // 4. Transmission Diagnostics Card
                item {
                    TestDiagnosticsCard(
                        txStats = txStats,
                        framesGenerated = testFramesGenerated,
                        targetFps = testFps
                    )
                }

                // 5. Latency Measurement Guide
                item {
                    LatencyGuideCard()
                }

                item {
                    Spacer(modifier = Modifier.height(24.dp))
                }
            }
        }
    }
}

/**
 * Isolated Composable observing testPatternBitmap.
 * Frame updates at 60 FPS only recompose this leaf Image, leaving the rest of the UI unaffected.
 */
@Composable
private fun IsolatedTestFeed(
    viewModel: CaptureViewModel,
    modifier: Modifier = Modifier
) {
    val bitmap by viewModel.testPatternBitmap.collectAsStateWithLifecycle()

    if (bitmap != null) {
        Image(
            bitmap = remember(bitmap) { bitmap!!.asImageBitmap() },
            contentDescription = "Latency Test Pattern",
            modifier = modifier,
            contentScale = ContentScale.Fit,
            filterQuality = FilterQuality.Medium
        )
    } else {
        Box(
            modifier = modifier,
            contentAlignment = Alignment.Center
        ) {
            Text(
                text = "Initializing Test Pattern...",
                color = Color(0xFF94A3B8),
                style = MaterialTheme.typography.bodyMedium
            )
        }
    }
}

